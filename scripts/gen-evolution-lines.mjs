function toDisplay(slug) {
  if (DISPLAY_OVERRIDES[slug]) return DISPLAY_OVERRIDES[slug];
  return slug
    .split("-")
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join(" ");
}

function walk(node, root, out) {
  const name = toDisplay(node.species.name);
  out[name] = root;
  for (const next of node.evolves_to ?? []) walk(next, root, out);
}

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.json();
}

async function main() {
  const map = {};
  let next = `${BASE}/evolution-chain?limit=100`;
  const chainUrls = [];
  while (next) {
    const page = await fetchJson(next);
    for (const r of page.results) chainUrls.push(r.url);
    next = page.next;
    process.stderr.write(`listed ${chainUrls.length} chains…\n`);
  }

  let i = 0;
  for (const url of chainUrls) {
    i += 1;
    const chain = await fetchJson(url);
    const rootSlug = chain.chain.species.name;
    const root = toDisplay(rootSlug);
    walk(chain.chain, root, map);
    if (i % 25 === 0 || i === chainUrls.length) {
      process.stderr.write(`fetched ${i}/${chainUrls.length}\n`);
    }
    // Be polite to PokeAPI.
    await new Promise((r) => setTimeout(r, 40));
  }

  const entries = Object.entries(map).sort(([a], [b]) => a.localeCompare(b));
  const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
  const file = `/* Auto-generated by scripts/gen-evolution-lines.mjs — do not edit by hand. */\n` +
    `export const SPECIES_TO_LINE_ROOT: Record<string, string> = {\n${body}\n};\n`;
  writeFileSync(OUT, file);
  process.stderr.write(`Wrote ${entries.length} species → ${OUT}\n`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
